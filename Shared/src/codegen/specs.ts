const numLit = (n: number, forceDot: boolean) => {
  if (!Number.isFinite(n)) return '0';
  const s = String(n);
  return forceDot && Number.isInteger(n) && !s.includes('e') ? s + '.0' : s;
};
const q = (s: string) => JSON.stringify(s);
const body = (lines: string[], pad: string) => lines.map((l) => (l ? pad + l : l)).join('\n');

