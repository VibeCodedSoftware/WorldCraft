// Marks shots leave behind (project settings: Project settings › Marks & blood, stored in logic.marks):
//  - bullet holes on walls and props (Fire hitscan);
//  - blood: a burst of small red chunks from the wound, and speckled patches on the floor under and behind the target
//    (Fire hitscan / Melee with their Blood option, or the Blood splatter block).
// Each kind has its own newest-N pool and lifetime (see addDecal). An object with noMarks takes no marks.
import { addDecal } from './blockImpl';
import { raycast } from './physics';
import type { Runtime } from './runtime';
import type { RInstance } from './world';

export interface BulletMarkSettings { enabled?: boolean; /** Across, in metres. */ size?: number; /** Seconds, 0 = stay. */ life?: number; max?: number }
export interface BloodSettings { enabled?: boolean; /** Chunks and patches, 1 = normal. */ intensity?: number; /** A floor patch across, in metres. */ size?: number; color?: string; /** Seconds, 0 = stay. */ life?: number; max?: number }
export interface MarkSettings { bullet?: BulletMarkSettings; blood?: BloodSettings }

export const BULLET_DEFAULTS: Required<BulletMarkSettings> = { enabled: true, size: 0.22, life: 30, max: 64 };
export const BLOOD_DEFAULTS: Required<BloodSettings> = { enabled: true, intensity: 1, size: 2, color: '#b01018', life: 45, max: 40 };
/** A decal image generated by the renderer (bloodSpeckle), not a file. */
export const BLOOD_IMAGE = 'proc:blood';

export const bulletSettings = (rt: Runtime) => ({ ...BULLET_DEFAULTS, ...rt.doc.marks?.bullet });
export const bloodSettings = (rt: Runtime) => ({ ...BLOOD_DEFAULTS, ...rt.doc.marks?.blood });

/** A bullet hole on a surface, unless holes are off or the surface takes no marks. */
export function bulletMark(rt: Runtime, on: RInstance, point: [number, number, number], normal: [number, number, number], image: string) {
  const s = bulletSettings(rt);
  if (!s.enabled || on.noMarks) return;
  addDecal(rt, on, point, normal, image, s.size * (0.85 + rt.rng.next() * 0.3), { life: s.life, max: s.max, pool: 'holes' });
}

/** Should this hit bleed, given the block's Blood option? */
export const bleeds = (mode: unknown, killed: boolean) => mode === 'hit and kill' || (mode === 'on hit') || (mode === 'on kill' && killed);

/** Middle of a target's collider: where a hit with no exact point bleeds from. */
function centre(rt: Runtime, v: RInstance): [number, number, number] {
  const b = rt.world.aabb(v);
  return [(b[0] + b[3]) / 2, (b[1] + b[4]) / 2, (b[2] + b[5]) / 2];
}

/**
 * Blood at a wound: chunks fly out along the shot and up, and patches land on the surfaces really under the spray.
 * Each patch is found by a ray down from the wound's height at a spot behind the target; a wall in the way shortens
 * the spray, and with no floor in reach (or a floor with noMarks) there is simply no patch.
 */
export function bloodSplatter(rt: Runtime, victim: RInstance, point?: [number, number, number], dir?: [number, number, number], killed = false) {
  const s = bloodSettings(rt);
  if (!s.enabled || s.intensity <= 0) return;
  const w = rt.world, xz = w.plane === 'xz';
  const at = point ?? centre(rt, victim);
  // Along the floor, away from the shot (no shot: any way).
  let dx = dir?.[0] ?? 0, dz = xz ? dir?.[2] ?? 0 : 0;
  const l = Math.hypot(dx, dz);
  if (l > 1e-4) { dx /= l; dz /= l; } else { const a = rt.rng.next() * Math.PI * 2; dx = Math.cos(a); dz = xz ? Math.sin(a) : 0; }
  const power = s.intensity * (killed ? 1.6 : 1);
  const solids = w.solids().filter((o) => o !== victim);
  const floorUnder = (x: number, y: number, z: number) => raycast(w, [x, y, z], [0, -1, 0], 8, solids, victim);

  const under = floorUnder(at[0], at[1], at[2]);
  const id = `fx:${rt.fxCounter++}`, e = rt.makeEmitter(id, 'blood');
  e.position = [at[0], at[1], at[2]];
  e.autoRemove = true;
  e.params = { ...e.params, burst: Math.round(e.params.burst * power), colorStart: s.color, colorEnd: s.color, direction: [dx * 0.75, 0.65, dz * 0.75], collideFloor: !!under, floorY: under ? under.point[1] : 0 };
  rt.emitters.set(id, e);

  const patches = Math.max(1, Math.round((killed ? 3 : 1) * Math.min(3, s.intensity)));
  for (let k = 0; k < patches; k++) {
    // The first lands near the target, later ones further along the spray, fanned out a little.
    const fan = (rt.rng.next() - 0.5) * 1.1, reach = (k === 0 ? 0.15 : k * 0.75) * s.size * (0.8 + rt.rng.next() * 0.4);
    const c = Math.cos(fan), sn = Math.sin(fan);
    const fx = dx * c - dz * sn, fz = xz ? dx * sn + dz * c : 0;
    const wall = reach > 0.05 ? raycast(w, at, [fx, 0, fz], reach, solids, victim) : null;
    const r = wall ? Math.max(0, wall.dist - 0.05) : reach;
    const hit = floorUnder(at[0] + fx * r, at[1], at[2] + fz * r);
    if (!hit || hit.inst.noMarks || hit.normal[1] < 0.3) continue;
    addDecal(rt, hit.inst, hit.point, hit.normal, BLOOD_IMAGE, s.size * (0.7 + rt.rng.next() * 0.6), { color: s.color, life: s.life, max: s.max, pool: 'blood' });
  }
}

/**
 * The picture of a floor patch: scattered hard one-pixel flecks, thick in a few lumps and thinning out to nothing at
 * the edge. Returns per-pixel coverage and brightness (0 = no fleck). Same seed, same picture.
 */
export function bloodSpeckle(seed: number, size = 192): { alpha: Uint8Array; shade: Uint8Array } {
  let h = (seed * 2654435761 + 1) >>> 0;
  const next = () => { h = (h + 0x6d2b79f5) >>> 0; let t = h; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const alpha = new Uint8Array(size * size), shade = new Uint8Array(size * size);
  const c = size / 2;
  const lumps = Array.from({ length: 3 + Math.floor(next() * 3) }, () => { const a = next() * Math.PI * 2, r = next() * c * 0.45; return { x: c + Math.cos(a) * r, y: c + Math.sin(a) * r, s: c * (0.18 + next() * 0.2) }; });
  const gauss = () => Math.sqrt(-2 * Math.log(1 - next() * 0.999)) * Math.cos(next() * Math.PI * 2);
  const flecks = Math.floor(size * size * 0.1);
  for (let n = 0; n < flecks; n++) {
    const l = lumps[Math.floor(next() * lumps.length)];
    const x = Math.round(l.x + gauss() * l.s), y = Math.round(l.y + gauss() * l.s);
    if (Math.hypot(x - c, y - c) > c - 3) continue; // stays clear of the edge, so a patch never shows a square outline
    const big = next() < 0.08 ? 2 : 1, b = 140 + Math.floor(next() * 115);
    for (let v = 0; v < big; v++) for (let u = 0; u < big; u++) { const k = (y + v) * size + x + u; alpha[k] = 255; shade[k] = b; }
  }
  return { alpha, shade };
}
